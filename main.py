"""
Streamlit user interface.

Provides a chat interface where users can ask questions,
retrieve relevant lecture content through FAISS semantic search,
and receive answers generated by Ollama.
"""

import streamlit as st
from src.retrieval import Retriever
from src.RAG import RAG


# Configure Streamlit page
st.set_page_config(
    page_title="RAG Streamlit Interface",
)

def main():  
    """
    Creates the streamlit user interface.
    """

    # Load retrieval data
    retriever = Retriever()
    rag = RAG(retriever)

    st.title("RAG Application")

    st.write(
        "Ask questions."
    )


    # Initialise chat history
    if "messages" not in st.session_state:
        st.session_state.messages = []



    # Display previous messages
    for message in st.session_state.messages:

        with st.chat_message(message["role"]):

            st.markdown(message["content"])



    # Handle new user questions
    if question := st.chat_input("Ask a question..."):


        st.session_state.messages.append(
            {
                "role": "user",
                "content": question
            }
        )


        with st.chat_message("user"):
            st.markdown(question)



        # Generate and display AI response
        with st.chat_message("assistant"):

            with st.spinner("Thinking..."):

                answer = rag.get_response(question)

                st.markdown(answer)



        # Store response in chat history
        st.session_state.messages.append(
            {
                "role": "assistant",
                "content": answer
            }
        )

if __name__ == "__main__":
    main()
