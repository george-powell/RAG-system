"""
Streamlit interface for the AI Physics Tutor.

Provides a chat interface where users can ask physics questions,
retrieve relevant lecture content through FAISS semantic search,
and receive answers generated by Ollama.
"""

import streamlit as st
import faiss
import pickle
from sentence_transformers import SentenceTransformer
import ollama


# Configure Streamlit page
st.set_page_config(
    page_title="Physics AI Tutor",
    page_icon="🧠"
)


@st.cache_resource
def load_resources():
    """
    Load the FAISS index, lecture chunks, and embedding model.

    Resources are cached so they are only loaded once when the
    Streamlit application starts.

    Returns:
        tuple: FAISS index, lecture chunks, and embedding model.
    """

    # Load vector database
    index = faiss.read_index("embeddings.index")

    # Load stored text chunks
    with open("chunks.pkl", "rb") as f:
        chunks = pickle.load(f)

    # Load embedding model
    embedder = SentenceTransformer("all-MiniLM-L6-v2")

    return index, chunks, embedder


# Load resources required for RAG pipeline
index, chunks, embedder = load_resources()


def get_response(question, index, chunks, embedder):
    """
    Generate a tutor response using retrieval augmented generation.

    The user's question is converted into an embedding, compared
    against stored lecture embeddings, and relevant context is
    passed to Ollama to generate a response.

    Args:
        question (str): User physics question.
        index: FAISS vector database.
        chunks (list): Stored lecture note chunks.
        embedder: SentenceTransformer embedding model.

    Returns:
        str: Generated tutor response.
    """

    # Convert question into embedding vector
    q_vector = embedder.encode([question]).astype("float32")


    # Retrieve most similar lecture chunks
    distances, indices = index.search(q_vector, k=5)


    # Extract text from retrieved chunks
    retrieved_chunks = [
        chunks[i]["text"]
        for i in indices[0]
    ]


    context = "\n\n".join(retrieved_chunks)


    # Construct RAG prompt
    prompt = f"""
You are a helpful university-level physics tutor.

Rules:
- Use clear section headers
- Use bullet points for steps
- Explain intuition clearly
- Keep answers structured and easy to follow
- Use simple readable maths
- Avoid raw LaTeX delimiters
- Only answer using the provided lecture notes
- If the question is outside scope, say so clearly

LECTURE NOTES:

{context}

QUESTION:

{question}
"""


    # Generate response using local LLM
    response = ollama.chat(
        model="llama3.1",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )


    return response["message"]["content"]



# -----------------------
# User interface
# -----------------------

st.title("Physics AI Tutor")

st.write(
    "Ask questions based on your lecture notes."
)


# Initialise chat history
if "messages" not in st.session_state:
    st.session_state.messages = []



# Display previous messages
for message in st.session_state.messages:

    with st.chat_message(message["role"]):

        st.markdown(message["content"])



# Handle new user questions
if question := st.chat_input("Ask a physics question..."):


    st.session_state.messages.append(
        {
            "role": "user",
            "content": question
        }
    )


    with st.chat_message("user"):
        st.markdown(question)



    # Generate and display AI response
    with st.chat_message("assistant"):

        with st.spinner("Thinking..."):

            answer = get_response(
                question,
                index,
                chunks,
                embedder
            )

            st.markdown(answer)



    # Store response in chat history
    st.session_state.messages.append(
        {
            "role": "assistant",
            "content": answer
        }
    )